#!/usr/bin/env python3
"""Writes bot/src/sensitivityData.ts: the damage each creature in backend/data/bestiary.json takes
from every element, as percentages from its TibiaWiki infobox (fields physicalDmgMod, earthDmgMod...).

Run from the repository root after bestiary.json changes:  python3 scripts/fetch-sensitivities.py
"""
import json
import re
import sys
import time
import urllib.parse
import urllib.request

BESTIARY = 'backend/data/bestiary.json'
OUTPUT = 'bot/src/sensitivityData.ts'
# Order of Tibia's in-game bestiary; must match ELEMENTS in bot/src/sensitivities.ts.
ELEMENTS = ['physical', 'earth', 'fire', 'death', 'energy', 'holy', 'ice']
API = 'https://tibia.fandom.com/api.php'


def fetch(titles):
    query = urllib.parse.urlencode({
        'action': 'query', 'prop': 'revisions', 'rvprop': 'content', 'rvslots': 'main',
        'format': 'json', 'redirects': 1, 'titles': '|'.join(titles),
    })
    request = urllib.request.Request(f'{API}?{query}', headers={'User-Agent': 'warden-bot-data/1.0'})
    with urllib.request.urlopen(request) as response:
        return json.load(response)['query']


def main():
    names = [m['name'] for m in json.load(open(BESTIARY, encoding='utf-8'))]
    mods = {}
    for i in range(0, len(names), 50):
        result = fetch(names[i:i + 50])
        # Map the page we got back to the title we asked for.
        back = {r['to']: r['from'] for r in result.get('redirects', [])}
        back.update({n['to']: n['from'] for n in result.get('normalized', [])})
        for page in result['pages'].values():
            if 'revisions' not in page:
                continue
            title = back.get(page['title'], page['title'])
            title = back.get(title, title)
            text = page['revisions'][0]['slots']['main']['*']
            values = []
            for element in ELEMENTS:
                match = re.search(r'\|\s*' + element + r'DmgMod\s*=\s*(-?\d+)\s*%', text, re.I)
                values.append(int(match.group(1)) if match else None)
            if None not in values:
                mods[title] = values
        time.sleep(0.5)

    missing = [n for n in names if n not in mods]
    if missing:
        print('No damage modifiers on TibiaWiki for: ' + ', '.join(missing), file=sys.stderr)

    lines = [
        '// Generated by scripts/fetch-sensitivities.py from TibiaWiki (CC BY-SA). Do not edit by hand.',
        '// Damage each creature takes, in percent, in the order of ELEMENTS in sensitivities.ts.',
        'export const SENSITIVITY_DATA: Record<string, readonly number[]> = {',
    ]
    for name in names:
        if name in mods:
            lines.append(f'  {json.dumps(name)}: [{", ".join(map(str, mods[name]))}],')
    lines.append('};')
    open(OUTPUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'{OUTPUT}: {len(mods)} of {len(names)} creatures')


if __name__ == '__main__':
    main()
