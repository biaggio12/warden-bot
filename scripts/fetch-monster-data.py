#!/usr/bin/env python3
"""Writes bot/src/monsterData.ts: base HP and the damage each creature in backend/data/bestiary.json
takes from every element, in percent, from https://mobs.vot.pl/api/mobs.

Run from the repository root after bestiary.json changes:  python3 scripts/fetch-monster-data.py
"""
import json
import re
import sys
import urllib.request

BESTIARY = 'backend/data/bestiary.json'
OUTPUT = 'bot/src/monsterData.ts'
API = 'https://mobs.vot.pl/api/mobs'
PAGE = 500
# Order of Tibia's in-game bestiary; must match ELEMENTS in bot/src/monsterStats.ts.
ELEMENTS = ['physical', 'earth', 'fire', 'death', 'energy', 'holy', 'ice']


def main():
    data = []
    while True:
        url = f'{API}?limit={PAGE}&offset={len(data)}'
        request = urllib.request.Request(url, headers={'User-Agent': 'warden-bot-data/1.0'})
        with urllib.request.urlopen(request) as response:
            body = json.load(response)
        data += body['data']
        if not body['data'] or len(data) >= body['meta']['total']:
            break
    mobs = {m['name'].lower(): m for m in data}

    names = [m['name'] for m in json.load(open(BESTIARY, encoding='utf-8'))]
    lines = [
        '// Generated by scripts/fetch-monster-data.py from mobs.vot.pl. Do not edit by hand.',
        '// Per creature: base HP (a Warden has three times as much) and the damage it takes, in percent,',
        '// in the order of ELEMENTS in monsterStats.ts.',
        'export const MONSTER_DATA: Record<string, { hp: number; damage: readonly number[] }> = {',
    ]
    missing = []
    for name in names:
        # The bestiary uses TibiaWiki titles: "Fish (Creature)" is plain "Fish" elsewhere.
        mob = mobs.get(name.lower()) or mobs.get(re.sub(r'\s*\((creature|basic)\)', '', name.lower()))
        if not mob or not mob.get('hp') or any(mob['sensitivity'].get(e) is None for e in ELEMENTS):
            missing.append(name)
            continue
        damage = ', '.join(str(mob['sensitivity'][e]) for e in ELEMENTS)
        lines.append(f'  {json.dumps(name)}: {{ hp: {mob["hp"]}, damage: [{damage}] }},')
    lines.append('};')

    if missing:
        print('Not in the API (or incomplete): ' + ', '.join(missing), file=sys.stderr)
    open(OUTPUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'{OUTPUT}: {len(names) - len(missing)} of {len(names)} creatures')


if __name__ == '__main__':
    main()
